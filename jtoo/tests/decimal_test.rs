use jtoo::{Encode, EncodeError, Encoder};
use rust_decimal_macros::dec;

#[test]
fn encode() {
    assert_eq!(
        dec!(-9_223_372_036_854_775_809).encode(),
        Err(EncodeError::OutOfRange)
    );
    assert_eq!(
        dec!(-9_223_372_036_854_775_808).encode().unwrap().as_str(),
        "-9_223_372_036_854_775_808.0"
    );
    assert_eq!(dec!(-1).encode().unwrap().as_str(), "-1.0");
    assert_eq!(
        dec!(-0.000_000_000_000_000_000_000_000_000_1)
            .encode()
            .unwrap()
            .as_str(),
        "-0.000_000_000_000_000_000_000_000_000_1"
    );
    assert_eq!(dec!(0).encode().unwrap().as_str(), "0.0");
    assert_eq!(
        dec!(0.000_000_000_000_000_000_000_000_000_1)
            .encode()
            .unwrap()
            .as_str(),
        "0.000_000_000_000_000_000_000_000_000_1"
    );
    assert_eq!(dec!(1).encode().unwrap().as_str(), "1.0");
    assert_eq!(
        dec!(9_223_372_036_854_775_807).encode().unwrap().as_str(),
        "9_223_372_036_854_775_807.0"
    );
    assert_eq!(
        dec!(9_223_372_036_854_775_808).encode(),
        Err(EncodeError::OutOfRange)
    );
}

#[test]
fn append() {
    for (value, exp, expected) in [
        // Zeros added before decimal point.
        (0, 0, "0.0"),
        (0, 1, "0.0"),
        (0, 2, "0.0"),
        (0, 3, "0.0"),
        (0, 4, "0.0"),
        (1, 1, "10.0"),
        (1, 2, "100.0"),
        (1, 3, "1_000.0"),
        (1, 4, "10_000.0"),
        (1, 5, "100_000.0"),
        (1, 6, "1_000_000.0"),
        (1, 7, "10_000_000.0"),
        (-1, 7, "-10_000_000.0"),
        (12, 7, "120_000_000.0"),
        (123, 7, "1_230_000_000.0"),
        (1234, 7, "12_340_000_000.0"),
        (-1234, 7, "-12_340_000_000.0"),
        // Exponent is zero.
        (1, 0, "1.0"),
        (-1, 0, "-1.0"),
        (12, 0, "12.0"),
        (-12, 0, "-12.0"),
        (123, 0, "123.0"),
        (-123, 0, "-123.0"),
        (1_234, 0, "1_234.0"),
        (-1_234, 0, "-1_234.0"),
        (12_345, 0, "12_345.0"),
        (-12_345, 0, "-12_345.0"),
        (123_456, 0, "123_456.0"),
        (-123_456, 0, "-123_456.0"),
        (1_234_567, 0, "1_234_567.0"),
        (-1_234_567, 0, "-1_234_567.0"),
        (i64::MAX, 0, "9_223_372_036_854_775_807.0"),
        (i64::MIN, 0, "-9_223_372_036_854_775_808.0"),
        // Zeros added after the decimal point.
        (0, -2, "0.00"),
        (0, -1, "0.0"),
        (1, -2, "0.01"),
        (-1, -2, "-0.01"),
        (10, -2, "0.10"),
        (1, -3, "0.001"),
        (1, -4, "0.000_1"),
        (10, -4, "0.001_0"),
        (100, -4, "0.010_0"),
        (1_000, -4, "0.100_0"),
        (10_000, -4, "1.000_0"),
        (1, -5, "0.000_01"),
        (1, -6, "0.000_001"),
        (1, -7, "0.000_000_1"),
        (-1, -7, "-0.000_000_1"),
        (1_234, -7, "0.000_123_4"),
        (-1_234, -7, "-0.000_123_4"),
        // No zeros added after decimal.
        (1, -1, "0.1"),
        (-1, -1, "-0.1"),
        (12, -2, "0.12"),
        (123, -3, "0.123"),
        (1_234, -4, "0.123_4"),
        (12_345, -5, "0.123_45"),
        (123_456, -6, "0.123_456"),
        (1_234_567, -7, "0.123_456_7"),
        (-1_234_567, -7, "-0.123_456_7"),
        (i64::MAX, -19, "0.922_337_203_685_477_580_7"),
        (i64::MIN, -19, "-0.922_337_203_685_477_580_8"),
        // Digits on both sides of decimal point.
        (10, -1, "1.0"),
        (12, -1, "1.2"),
        (123, -1, "12.3"),
        (1_234, -1, "123.4"),
        (12_345, -1, "1_234.5"),
        (10, -2, "0.10"),
        (123_456, -2, "1_234.56"),
        (1_234_567, -3, "1_234.567"),
        (12_345_678, -4, "1_234.567_8"),
        (12_345_678, -5, "123.456_78"),
        (12_345_678, -6, "12.345_678"),
        (12_345_678, -7, "1.234_567_8"),
        (i64::MAX, -18, "9.223_372_036_854_775_807"),
        (i64::MIN, -18, "-9.223_372_036_854_775_808"),
    ] {
        let mut encoder = Encoder::new();
        encoder.append_decimal(value, exp).unwrap();
        assert_eq!(encoder.as_str(), Ok(expected), "value={value} exp={exp}");
    }
}

#[test]
fn unclosed_string() {
    let mut encoder = Encoder::new();
    encoder.open_string().unwrap();
    assert_eq!(
        encoder.append_decimal(0, 0),
        Err(EncodeError::UnclosedString)
    );
}

#[test]
fn in_list() {
    let mut encoder = Encoder::new();
    encoder.open_list().unwrap();
    encoder.append_decimal(3, 2).unwrap();
    encoder.append_bool(true).unwrap();
    encoder.close_list().unwrap();
    assert_eq!(encoder.as_str(), Ok("[300.0,T]"));
}
